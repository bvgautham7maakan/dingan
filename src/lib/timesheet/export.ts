import "server-only";
import ExcelJS from "exceljs";
import { readFileSync } from "fs";
import path from "path";
import type { Timesheet } from "./build";
import { LEAVE_RULES } from "./rules";

/**
 * Writes the timesheet in the same layout as "KEM Timesheet 26-Aug to 25-Sep 2026.xlsx":
 * Summary, Settings, Employees, Daily Log, Timesheet (+ Site hours for moves between sites).
 * Values are written (not formulas). Money columns keep their headers and stay blank:
 * salaries are not held in this app.
 */
const COMPANY = "Kahraba Electromechanical Services LLC";
const FOOTER = "Kahraba Electromechanical Services LLC · Musaffah, Abu Dhabi, UAE · +971 2 546 9810 · info@kahrabaelectromechanical.com";
const CYAN = "FF00B4F0";
const ALT = "FFF0FAFF";
const HOURS = "0.0;\\-0.0;\\-";
const FONT = { name: "Arial", size: 10 };

const MON = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
const WD = ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"];
const dmy = (iso: string) => {
  const [y, m, d] = iso.split("-");
  return `${d}-${MON[Number(m) - 1]}-${y}`;
};
const asDate = (iso: string) => {
  const [y, m, d] = iso.split("-").map(Number);
  return new Date(Date.UTC(y, m - 1, d));
};

function header(ws: ExcelJS.Worksheet, rowNo: number, headers: string[]) {
  const row = ws.getRow(rowNo);
  headers.forEach((h, i) => {
    const c = row.getCell(i + 1);
    c.value = h;
    // Black on cyan: same contrast rule as the app screens.
    c.font = { ...FONT, bold: true, color: { argb: "FF000000" } };
    c.fill = { type: "pattern", pattern: "solid", fgColor: { argb: CYAN } };
    c.alignment = { vertical: "middle", wrapText: true };
  });
  row.height = 28;
}

function band(ws: ExcelJS.Worksheet, from: number, to: number, cols: number) {
  for (let r = from; r <= to; r++) {
    const row = ws.getRow(r);
    for (let c = 1; c <= cols; c++) {
      const cell = row.getCell(c);
      cell.font = { ...FONT, ...(cell.font ?? {}) };
      if ((r - from) % 2 === 1) cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: ALT } };
    }
  }
}

function title(ws: ExcelJS.Worksheet, a1: string, a2?: string) {
  ws.getCell("A1").value = a1;
  ws.getCell("A1").font = { name: "Arial", size: 14, bold: true, color: { argb: CYAN } };
  if (a2) {
    ws.getCell("A2").value = a2;
    ws.getCell("A2").font = { name: "Arial", size: 11, bold: true };
  }
}

export async function timesheetWorkbook(ts: Timesheet): Promise<Buffer> {
  const wb = new ExcelJS.Workbook();
  wb.creator = "KEM Site";
  wb.created = new Date();
  const period = `${dmy(ts.start)} to ${dmy(ts.end)}`;
  const opts = { properties: { tabColor: { argb: CYAN } } };

  // ── Summary ──
  const sum = wb.addWorksheet("Summary", opts);
  title(sum, COMPANY, `Workers timesheet summary  |  ${period}`);
  try {
    const logo = wb.addImage({ buffer: readFileSync(path.join(process.cwd(), "public/logo.png")) as unknown as ExcelJS.Buffer, extension: "png" });
    sum.addImage(logo, { tl: { col: 3.2, row: 0.2 }, ext: { width: 160, height: 34 } });
  } catch {
    /* logo is optional */
  }
  header(sum, 4, ["Metric", "Value", "Note"]);
  const g = ts.grand;
  const notEntered = ts.workers.flatMap((w) => w.days).filter((d) => d.status === "" && !/^Employee/.test(d.name)).length;
  const metrics: [string, number | string, string][] = [
    ["Employees on roll", ts.workers.filter((w) => w.status === "ACTIVE").length, "From Employees sheet"],
    ["Worker-days present", g.daysWorked, "Status P in Daily Log"],
    ["Normal hours", g.normal, "Mon–Sat, 8 hrs/day"],
    ["OT hours @ 1.25 (normal days)", g.ot125, "Hours beyond 9-hr shift"],
    ["OT hours @ 1.5 (Sunday / PH)", g.ot150, "All hours worked on Sun/PH, lunch deducted"],
    ["Annual leave days", g.alDays, ""],
    ["Sick leave days", g.sickDays, ""],
    ["Other leave days (CL/LV/A)", g.otherLeaveDays, "Unpaid – deduct Basic ÷ 30 per day"],
    ["Paid leave days (AL/SL)", g.paidLeaveDays, "Paid – annual and sick / medical leave"],
    ["Total OT amount (AED)", "", "Fills in once basic salaries are entered"],
    ["Total gross (AED)", "", "Basic + OT"],
    ["Days not yet entered", notEntered, "Blank status rows (placeholder employees excluded)"],
  ];
  metrics.forEach((m, i) => {
    const r = sum.getRow(5 + i);
    r.values = m;
    if (typeof m[1] === "number" && /hours/i.test(m[0])) r.getCell(2).numFmt = "#,##0.0";
  });
  band(sum, 5, 4 + metrics.length, 3);
  sum.getCell(`A${7 + metrics.length}`).value = `Generated by KEM Site on ${dmy(new Date().toISOString().slice(0, 10))} from site attendance.`;
  sum.getCell(`A${9 + metrics.length}`).value = FOOTER;
  sum.columns = [{ width: 34 }, { width: 14 }, { width: 50 }];

  // ── Settings ──
  const st = wb.addWorksheet("Settings", opts);
  title(st, COMPANY, "Timesheet settings");
  header(st, 3, ["Parameter", "Value", "Note / source"]);
  const s = ts.settings;
  const settingsRows: [string, unknown, string][] = [
    ["Period start", asDate(ts.start), `Cycle runs ${s.cycleStartDay}th to ${s.cycleStartDay - 1}th`],
    ["Period end", asDate(ts.end), ""],
    ["Normal paid hours / day (Mon–Sat)", s.normalHours, "9 hr shift incl. 1 hr lunch"],
    ["Lunch break (hrs)", s.lunchHours, ""],
    ["Deduct lunch only if shift longer than (hrs)", s.lunchAfterHours, ""],
    ["OT rate — normal day (x)", s.otNormalRate, ""],
    ["OT rate — Sunday / public holiday (x)", s.otHolidayRate, ""],
    ["Days per month (hourly rate divisor)", 30, "Hourly rate = Basic ÷ 30 ÷ 8"],
  ];
  settingsRows.forEach((v, i) => {
    const r = st.getRow(4 + i);
    r.values = v as ExcelJS.CellValue[];
    if (v[1] instanceof Date) r.getCell(2).numFmt = "dd-mmm-yyyy";
  });
  band(st, 4, 11, 3);
  st.getCell("A14").value = "Public holidays";
  st.getCell("A14").font = { ...FONT, bold: true };
  header(st, 15, ["Date", "Name"]);
  ts.holidays.forEach((h, i) => {
    const r = st.getRow(16 + i);
    r.values = [asDate(h.date), h.name];
    r.getCell(1).numFmt = "dd-mmm-yyyy";
  });
  // leave pay rules (confirmed by KEM)
  const lr = 18 + Math.max(ts.holidays.length, 10);
  st.getCell(`A${lr}`).value = "Leave codes";
  st.getCell(`A${lr}`).font = { ...FONT, bold: true };
  header(st, lr + 1, ["Code", "Meaning", "Paid"]);
  LEAVE_RULES.forEach((r, i) => {
    st.getRow(lr + 2 + i).values = [r.code, r.meaning, r.paid === null ? "n/a" : r.paid ? "Yes" : "No"];
  });
  band(st, lr + 2, lr + 1 + LEAVE_RULES.length, 3);
  st.columns = [{ width: 42 }, { width: 14 }, { width: 44 }];

  // ── Employees ──
  const em = wb.addWorksheet("Employees", opts);
  header(em, 1, ["Emp ID", "Name", "Status", "Last day", "Basic salary (AED/month)", "Hourly rate (AED)", "Remarks"]);
  ts.workers.forEach((w, i) => {
    const r = em.getRow(2 + i);
    r.values = [w.empCode, w.name, w.status === "LEFT" ? "Left" : "Active", w.lastDay ? asDate(w.lastDay) : null, null, null, w.status === "PLACEHOLDER" ? "Add name" : null];
    if (w.lastDay) r.getCell(4).numFmt = "dd-mmm-yyyy";
  });
  band(em, 2, 1 + ts.workers.length, 7);
  em.columns = [{ width: 9 }, { width: 24 }, { width: 10 }, { width: 13 }, { width: 14 }, { width: 12 }, { width: 40 }];

  // ── Daily Log ──
  const dl = wb.addWorksheet("Daily Log", opts);
  header(dl, 1, ["Date", "Day", "Day type", "Emp ID", "Name", "Status", "Time in", "Time out", "Site", "Shift span (hrs)", "Worked (hrs)", "Normal (hrs)", "OT 1.25 (hrs)", "OT 1.5 (hrs)", "Reported OT (hrs)", "Remarks", "Key"]);
  let r = 2;
  for (const day of ts.days) {
    for (const w of ts.workers) {
      const d = w.days.find((x) => x.date === day)!;
      const row = dl.getRow(r++);
      row.values = [
        asDate(day), WD[asDate(day).getUTCDay()], d.dayType, d.empCode, d.name, d.status || null, d.timeIn, d.timeOut, d.site,
        d.hours.span, d.hours.worked, d.hours.normal, d.hours.ot125, d.hours.ot150, null, d.remarks,
        `${d.empCode}|${day.replaceAll("-", "")}`,
      ];
      row.getCell(1).numFmt = "d-mmm-yy";
      for (let c = 10; c <= 14; c++) row.getCell(c).numFmt = HOURS;
    }
  }
  band(dl, 2, r - 1, 17);
  dl.views = [{ state: "frozen", ySplit: 1 }];
  dl.autoFilter = { from: "A1", to: `Q${r - 1}` };
  dl.columns = [10, 6, 9, 8, 22, 7, 8, 8, 16, 10, 10, 10, 10, 10, 10, 40, 14].map((width) => ({ width }));

  // ── Timesheet ──
  const tsh = wb.addWorksheet("Timesheet", opts);
  title(tsh, COMPANY, `Workers timesheet  |  ${period}`);
  tsh.getCell("A3").value =
    "Cell = hours worked (normal + OT) · codes: OFF Sunday/holiday off · AL annual leave · SL sick · CL leave · LV leave (type TBC) · A absent · LEFT · blank = not entered. Bold black day header = Sunday/PH.";
  tsh.getCell("A3").font = { ...FONT, italic: true, size: 9 };
  const nDays = ts.days.length;
  const wdRow = tsh.getRow(4);
  ts.days.forEach((d, i) => {
    const c = wdRow.getCell(3 + i);
    c.value = WD[asDate(d).getUTCDay()];
    c.font = { ...FONT, bold: ts.dayTypes[i] !== "Normal" };
    c.alignment = { horizontal: "center" };
  });
  header(tsh, 5, [
    "ID", "Name", ...ts.days.map((d) => d.slice(8)),
    "Days worked", "Normal hrs", "OT 1.25 hrs", "OT 1.5 hrs", "AL days", "Sick days", "Other leave days",
    "Basic (AED)", "Hourly rate", "OT 1.25 amt (AED)", "OT 1.5 amt (AED)", "Total OT (AED)", "Gross (AED)",
  ]);
  ts.workers.forEach((w, i) => {
    const row = tsh.getRow(6 + i);
    const t = w.totals;
    row.values = [w.empCode, w.name, ...w.cells, t.daysWorked, t.normal, t.ot125, t.ot150, t.alDays, t.sickDays, t.otherLeaveDays];
    w.cells.forEach((c, j) => {
      const cell = row.getCell(3 + j);
      cell.alignment = { horizontal: "center" };
      if (typeof c === "number" && c > 8) cell.font = { ...FONT, bold: true, color: { argb: CYAN } };
    });
    for (let c = 4 + nDays; c <= 6 + nDays; c++) row.getCell(c).numFmt = "0.0";
  });
  const lastW = 5 + ts.workers.length;
  band(tsh, 6, lastW, 2 + nDays + 13);
  const tot = tsh.getRow(lastW + 1);
  const g2 = ts.grand;
  tot.values = ["TOTAL", "", ...ts.days.map(() => null), g2.daysWorked, g2.normal, g2.ot125, g2.ot150, g2.alDays, g2.sickDays, g2.otherLeaveDays];
  tot.font = { ...FONT, bold: true };
  const present = tsh.getRow(lastW + 2);
  present.values = ["Present", "", ...ts.days.map((_, j) => ts.workers.filter((w) => typeof w.cells[j] === "number").length)];
  present.font = { ...FONT, italic: true };
  tsh.getCell(`A${lastW + 4}`).value = "Gross = Basic + OT − unpaid days (CL / LV / A, see 'Other leave days') × Basic ÷ 30. AL and SL are paid. Cyan bold cell = worked > 8 hrs.";
  tsh.columns = [{ width: 7 }, { width: 22 }, ...ts.days.map(() => ({ width: 5 })), ...Array(13).fill({ width: 10 })];
  tsh.views = [{ state: "frozen", xSplit: 2, ySplit: 5 }];

  // ── Site hours (hours split by manpower moves) ──
  const sh = wb.addWorksheet("Site hours", opts);
  title(sh, COMPANY, `Hours by site  |  ${period}`);
  header(sh, 4, ["Site", "Man-days", "Normal hrs", "OT 1.25 hrs", "OT 1.5 hrs"]);
  [...ts.siteTotals.entries()]
    .sort((a, b) => a[0].localeCompare(b[0]))
    .forEach(([site, v], i) => {
      const row = sh.getRow(5 + i);
      row.values = [site, Math.round(v.manDays * 100) / 100, v.normal, v.ot125, v.ot150];
      for (let c = 2; c <= 5; c++) row.getCell(c).numFmt = "0.00";
    });
  band(sh, 5, 4 + ts.siteTotals.size, 5);
  sh.getCell(`A${6 + ts.siteTotals.size}`).value = "A worker moved during the day is split by time spent at each site.";
  sh.columns = [{ width: 22 }, { width: 12 }, { width: 12 }, { width: 12 }, { width: 12 }];

  return Buffer.from(await wb.xlsx.writeBuffer());
}
